// Builds the installable web app into ../docs for GitHub Pages:
// everything in public/, plus a service worker that keeps the whole game on the phone for offline play.
// Usage: node tools/build-pages.mjs
import { cpSync, rmSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
const OUT = '../docs';
rmSync(OUT, { recursive: true, force: true });
cpSync('public', OUT, { recursive: true });
const files = [], hash = createHash('sha256');
const walk = d => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else { const r = relative(OUT, p).split('\\').join('/'); if (/\.(txt|md)$|LICENSE|OrbitControls/.test(r)) continue; files.push(r); hash.update(r); hash.update(readFileSync(p)); } } };
walk(OUT);
const version = hash.digest('hex').slice(0, 12);
writeFileSync(join(OUT, 'sw.js'), `// Offline cache for Emberfall (generated by tools/build-pages.mjs)
const CACHE = 'emberfall-${version}';
const FILES = ${JSON.stringify(['./', ...files])};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(r => r || fetch(e.request)));
});
`);
writeFileSync(join(OUT, '.nojekyll'), '');
console.log(`docs/: ${files.length} files, version ${version}`);
