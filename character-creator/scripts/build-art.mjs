// Extracts only the illustrations the quiz uses from Fluent Emoji Flat (MIT, Microsoft)
// into a small generated module, so the full 3,000-icon set never ships to students.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/fluent-emoji-flat/icons.json'), 'utf8'));

const names = `
glowing-star eyes collision zany-face handshake cookie
person fox robot ghost alien teapot dragon
cityscape castle rocket school desert water-wave national-park
face-with-tears-of-joy crossed-swords magnifying-glass-tilted-left hot-beverage flying-saucer jack-o-lantern mending-heart
brain performing-arts fire light-bulb red-heart mountain
crown anxious-face-with-sweat high-voltage green-heart pleading-face shield snail
trophy house key compass adhesive-bandage sports-medal seedling
vs-button locked stop-sign thought-balloon hourglass-not-done broken-heart cyclone
sparkles pencil artist-palette clapper-board party-popper
`.split(/\s+/).filter(Boolean);

const out = {};
for (const n of names) {
  const icon = set.icons[n] ?? set.icons[set.aliases?.[n]?.parent];
  if (!icon) throw new Error(`Missing illustration: ${n}`);
  out[n] = icon.body;
}
const banner = `// GENERATED by scripts/build-art.mjs - do not edit by hand.
// Artwork: Fluent Emoji (flat) (c) Microsoft Corporation, MIT License.
// https://github.com/microsoft/fluentui-emoji - see THIRD_PARTY_NOTICES.md
`;
writeFileSync(new URL('../src/art/emoji.generated.ts', import.meta.url),
  `${banner}export const EMOJI: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(`Wrote ${names.length} illustrations.`);
